function makeEpochs(
  pmRaMasYr: number,
  pmDecMasYr: number,
  fluxScales: [number, number, number, number],
): EpochData[] {
  const meta: Array<{
    epoch: 1 | 2 | 3 | 4;
    label: string;
    dateLabel: string;
    mjd: number;
  }> = [
    { epoch: 1, label: 'T1', dateLabel: 'May 2025', mjd: 60809.18 },
    { epoch: 2, label: 'T2', dateLabel: 'Aug 2025', mjd: 60901.46 },
    { epoch: 3, label: 'T3', dateLabel: 'Nov 2025', mjd: 60994.8 },
    { epoch: 4, label: 'T4', dateLabel: 'Dec 2025', mjd: 61030.12 },
  ];

  const baseMjd = meta[0].mjd;

  return meta.map((m, i) => {
    const dtYears = (m.mjd - baseMjd) / 365.25;
    return {
      epoch: m.epoch,
      label: m.label,
      dateLabel: m.dateLabel,
      mjd: m.mjd,
      raShiftArcsec: Number(((pmRaMasYr / 1000) * dtYears).toFixed(4)),
      decShiftArcsec: Number(((pmDecMasYr / 1000) * dtYears).toFixed(4)),
      fluxScale: fluxScales[i],
    };
  });
}

